using System;
using System.Collections.Generic;
using System.Drawing;
using System.Drawing.Imaging;
using System.IO;
using System.Web.Script.Serialization;

// Exports the artwork for docs/index.html: one static sprite per role, one
// horizontal strip of unique frames per animation, and a step timeline.
namespace CursorForge
{
    internal static class Web
    {
        public static void Export(string root, string outDir)
        {
            const int size = 128;
            string sprites = Path.Combine(outDir, "sprites");
            Directory.CreateDirectory(sprites);
            JavaScriptSerializer json = new JavaScriptSerializer { MaxJsonLength = int.MaxValue };
            Dictionary<string, object> manifest = (Dictionary<string, object>)json.DeserializeObject(File.ReadAllText(Path.Combine(root, "cursor-manifest.json")));
            Dictionary<string, object> roles = (Dictionary<string, object>)manifest["roles"];
            Dictionary<string, object> effects = (Dictionary<string, object>)manifest["effects"];
            List<object> list = new List<object>();
            long bytes = 0;
            foreach (string role in Program.Roles)
            {
                Dictionary<string, object> info = (Dictionary<string, object>)roles[role];
                object[] hot = (object[])((Dictionary<string, object>)info["hotspots"])[size.ToString()];
                CurFile cur = CurFile.Read(Path.Combine(root, role + ".cur"));
                string staticPath = Path.Combine(sprites, role + ".png");
                cur.BySize(size).Pixels.SavePng(staticPath);
                bytes += new FileInfo(staticPath).Length;
                Dictionary<string, object> entry = new Dictionary<string, object>();
                entry["role"] = role;
                entry["label"] = info["label"];
                entry["hotspot"] = new[] { Convert.ToInt32(hot[0]), Convert.ToInt32(hot[1]) };
                entry["image"] = "sprites/" + role + ".png";
                entry["classic"] = Program.IsAnimated(role, "Classic");
                entry["lively"] = Program.IsAnimated(role, "Lively");
                string aniPath = Path.Combine(root, role + ".ani");
                if (File.Exists(aniPath))
                {
                    AniFile ani = AniFile.Read(aniPath);
                    string strip = Path.Combine(sprites, role + "-frames.png");
                    using (Bitmap b = new Bitmap(size * ani.Frames.Count, size, PixelFormat.Format32bppArgb))
                    {
                        using (Graphics g = Graphics.FromImage(b))
                        {
                            g.CompositingMode = System.Drawing.Drawing2D.CompositingMode.SourceCopy;
                            for (int f = 0; f < ani.Frames.Count; f++)
                                using (Bitmap frame = ani.Frames[f].BySize(size).Pixels.ToBitmap()) g.DrawImageUnscaled(frame, f * size, 0);
                        }
                        b.Save(strip, ImageFormat.Png);
                    }
                    bytes += new FileInfo(strip).Length;
                    List<int[]> steps = new List<int[]>();
                    for (int s = 0; s < ani.StepCount; s++) steps.Add(new[] { ani.FrameAt(s), ani.RateAt(s) }); // [frame, duration in 1/60 s]
                    Dictionary<string, object> anim = new Dictionary<string, object>();
                    anim["strip"] = "sprites/" + role + "-frames.png";
                    anim["frames"] = ani.Frames.Count;
                    anim["steps"] = steps;
                    anim["effect"] = effects.ContainsKey(role) ? effects[role] : "";
                    entry["animation"] = anim;
                }
                list.Add(entry);
            }
            Dictionary<string, object> data = new Dictionary<string, object>();
            data["name"] = manifest["name"];
            data["spriteSize"] = size;
            data["roles"] = list;
            File.WriteAllText(Path.Combine(outDir, "cursors.js"),
                "// Generated by tools/CursorForge (web). Do not edit by hand.\nwindow.SOFT_BLACK = " + json.Serialize(data) + ";\n");
            Console.WriteLine("web assets: {0} roles, {1:N0} bytes of sprites -> {2}", list.Count, bytes, outDir);
        }
    }
}
